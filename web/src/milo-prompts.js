export function filterPrompts(items,category='전체',query=''){
 const q=String(query||'').toLocaleLowerCase()
 return items.filter(p=>(category==='전체'||p.category===category)&&
 (!q||[p.title,p.category,p.guide].join(' ').toLocaleLowerCase().includes(q)))
}
export function parseUserPrompts(uid,storage){
 try{const val=JSON.parse(storage.getItem('milosoft-prompts:'+uid)||'[]');return Array.isArray(val)?val.filter(x=>typeof x?.title==='string'&&typeof x?.text==='string').slice(0,200):[]}catch{return []}
}
export function saveUserPrompt(uid,entry,storage){
 const current=parseUserPrompts(uid,storage)
 const record={id:'custom-'+Date.now().toString(36),category:CATEGORIES.includes(entry.category)?entry.category:'행정',
  title:String(entry.title||'').trim().slice(0,80),text:String(entry.text||'').trim().slice(0,5000),
  guide:'사용자 저장 프롬프트'}
 if(!record.title||!record.text)throw Error('제목과 프롬프트를 입력해 주세요.')
 current.unshift(record);storage.setItem('milosoft-prompts:'+uid,JSON.stringify(current.slice(0,200)))
 return record
}
